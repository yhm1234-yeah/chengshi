export function getDocTitle(docId: string): string {
  return KNOWLEDGE_DOCS.find((d) => d.id === docId)?.title ?? '未知文档';
}

export function buildKnowledge(): { docs: KnowledgeDoc[]; chunks: KnowledgeChunk[] } {
  const now = new Date().toISOString();
  const docs: KnowledgeDoc[] = KNOWLEDGE_DOCS.map((d) => ({
    ...d,
    status: 'active',
    createdAt: now
  }));
  const chunks: KnowledgeChunk[] = KNOWLEDGE_CHUNKS.map((c, i) => ({
    id: `kc-${String(i + 1).padStart(3, '0')}`,
    docId: c.docId,
    chapter: c.chapter,
    clause: c.clause,
    content: c.content,
    keywords: c.keywords,
    embedding: [],
    status: 'active',
    effectiveDate: KNOWLEDGE_DOCS.find((d) => d.id === c.docId)?.effectiveDate ?? '2026-01-01'
  }));
  return { docs, chunks };
}
